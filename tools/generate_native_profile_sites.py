#!/usr/bin/env python3
"""Generate gangstar_native_profile_sites.h from the supported libgl2jni.so.

Selects engine functions by demangled name (loading, parsing, streaming,
creation and update paths), keeps only ARM functions whose first two
instructions can be relocated (no branches, no PC use except a literal LDR)
and that no branch targets at +4, and excludes every symbol the loader
already hooks.

Usage: generate_native_profile_sites.py path/to/libgl2jni.so [output-dir]
Writes gangstar_native_profile_sites.h and native_profile_sites.txt (address
-> demangled name, read by native_profile_report.py) to output-dir, default
work/generated. Both are derived from the game binary and are not committed;
CMake runs this automatically for GANGSTAR_NATIVE_PROFILER=ON builds.
"""
import re, struct, subprocess, sys
from pathlib import Path
root = Path(__file__).resolve().parents[1]
if len(sys.argv) not in (2, 3): sys.exit(__doc__)
elf = Path(sys.argv[1]).read_bytes()
out_dir = Path(sys.argv[2]) if len(sys.argv) == 3 else root / 'work/generated'
out_dir.mkdir(parents=True, exist_ok=True)
def u32(off): return struct.unpack_from('<I', elf, off)[0]
# ELF section headers -> .text and symbol tables
shoff, shentsize, shnum, shstrndx = u32(0x20), struct.unpack_from('<H', elf, 0x2e)[0], struct.unpack_from('<H', elf, 0x30)[0], struct.unpack_from('<H', elf, 0x32)[0]
secs = [struct.unpack_from('<IIIIIIIIII', elf, shoff + i * shentsize) for i in range(shnum)]
strtab_off = secs[shstrndx][4]
def secname(s): return elf[strtab_off + s[0]:elf.index(b'\0', strtab_off + s[0])].decode()
text = next(s for s in secs if secname(s) == '.text')
TEXT_LO, TEXT_HI = text[3], text[3] + text[5]
assert text[3] == text[4], 'expected .text vaddr == file offset'
syms = {}
for s in secs:
    if s[1] not in (2, 11): continue          # SYMTAB / DYNSYM
    link = secs[s[6]]
    for i in range(s[5] // 16):
        name_off, value, size, info, other, shndx = struct.unpack_from('<IIIBBH', elf, s[4] + i * 16)
        if info & 15 != 2 or not shndx or value % 4 or size < 96 or not TEXT_LO <= value < TEXT_HI: continue
        name = elf[link[4] + name_off:elf.index(b'\0', link[4] + name_off)].decode()
        syms.setdefault(value, (name, size))
names = [v[0] for v in syms.values()]
demangled = dict(zip(names, subprocess.run(['c++filt'], input='\n'.join(names), capture_output=True, text=True).stdout.splitlines()))
loader = set(re.findall(r'"(_Z[A-Za-z0-9_]+)"', '\n'.join(p.read_text(errors='replace') for p in (root / 'source').rglob('*.[ch]'))))
def relocatable(w):
    if w >> 28 != 0xE: return False
    op = (w >> 25) & 7; rn, rd, rs, rm = (w >> 16) & 15, (w >> 12) & 15, (w >> 8) & 15, w & 15
    if op in (0, 1):
        if op == 0 and (w & 0x0ff000f0) in (0x01200010, 0x01200030): return False
        return rn != 15 and rd != 15 and (op == 1 or (rm != 15 and rs != 15))
    if op in (2, 3):
        if op == 3 and (w >> 4) & 1: return False
        if rd == 15: return False
        if rn == 15: return op == 2 and (w & 0x0f7f0000) == 0x051f0000   # ldr rd,[pc,#+-imm]
        return not (op == 3 and rm == 15)
    if op == 4: return rn != 15 and not ((w >> 20) & 1 and (w >> 15) & 1)
    return (w & 0x0fbf0f00) == 0x0d2d0b00                                # vpush
targets = set()
for a in range(TEXT_LO, TEXT_HI, 4):
    w = u32(a)
    if (w >> 25) & 7 == 5:
        imm = w & 0xffffff
        if imm & 0x800000: imm -= 1 << 24
        targets.add(a + 8 + imm * 4)
want = re.compile(r'(load|Load|init\b|Init|create|Create|read|Read|parse|Parse|open|Open|decompress|inflate|Inflate|stream|Stream|build|Build|spawn|Spawn|register|Register|Update|update|unload|Unload|compile|Compile|Resource|Texture|Mesh|Material|Collada|DDS|Image|Decode|decode)')
skip = re.compile(r'(png|operator|~|::Get|::get|::Is|::is|::Set|::set|std::|boost::|__|Clone|clone|vector|basic_string|SAllocator|TClass|Delegate)')
sites = []
for addr, (name, size) in sorted(syms.items()):
    d = demangled[name]
    if name in loader or not want.search(d) or skip.search(d): continue
    w0, w1 = u32(addr), u32(addr + 4)
    if relocatable(w0) and relocatable(w1) and addr + 4 not in targets:
        sites.append((addr, w0, w1, d))
assert len(sites) < 4096
out = ['/* Generated by tools/generate_native_profile_sites.py. Do not edit. */',
       '#ifndef GANGSTAR_NATIVE_PROFILE_SITES_H', '#define GANGSTAR_NATIVE_PROFILE_SITES_H',
       '#include <stdint.h>', 'typedef struct { uint32_t offset, w0, w1; } RioProfSite;',
       '#define RIO_PROF_SITES %d' % len(sites), 'static const RioProfSite rio_prof_sites[RIO_PROF_SITES] = {']
out += ['  {0x%07x,0x%08x,0x%08x},' % s[:3] for s in sites]
out += ['};', '#endif', '']
(out_dir / 'gangstar_native_profile_sites.h').write_text('\n'.join(out))
(out_dir / 'native_profile_sites.txt').write_text(''.join('%#x %s\n' % (s[0], s[3]) for s in sites))
print('native profile sites:', len(sites))
