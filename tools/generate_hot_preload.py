#!/usr/bin/env python3
"""Generate source/gangstar_texture_hot_preload.h from the game's OBB index.

Lists every plain 512x512 district texture the engine streams on the frame
thread: canonical _packetc/ entries of exactly 174904 bytes (a 512x512 ETC1
DDS with its full mip chain), uncompressed in the archive, whose name is a
district/world texture, and which the port does not already handle through
the reduced-LOD manifest, the lightmap path or the retained texture pins.
The port loads them into its reload cache on the world loading screen.

Reads only the archive directory (no texture data). Usage:
  python3 tools/generate_hot_preload.py [path/to/main.12030...obb ...]
Default: ../com.gameloft.android.ANMP.GloftG4HM/*.obb next to the port folder.
"""
import re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from inventory_textures import entries, WORLD

ROOT = Path(__file__).resolve().parents[1]
ENTRY_BYTES = 174904
BUDGET = 28 * 1024 * 1024        # stays below RIO_HOT_LIMIT, leaving room for gameplay reloads
# Non-district names seen streaming in the same way while driving.
EXTRA = {'tile.tga', 'alphablend_rio.tga', 'alphablend_rio_alpha.tga', 'grass.tga', 'grass_alpha.tga'}

def quoted_names(header):
    return set(re.findall(r'"([^"]+\.(?:tga|bmp))"', (ROOT / 'source' / header).read_text()))

def main():
    paths = [Path(p) for p in sys.argv[1:]] or sorted((ROOT.parent / 'com.gameloft.android.ANMP.GloftG4HM').glob('*.obb'))
    if not paths:
        sys.exit(__doc__)
    reduced = quoted_names('gangstar_world_texture_manifest.h')
    pinned = quoted_names('gangstar_texture_pin.h')
    chosen = {}
    for path in paths:
        for e in entries(path):
            name = e['name']
            if not name.lower().startswith('_packetc/') or name.count('/') != 1:
                continue
            base = name.split('/', 1)[1]
            low = base.lower()
            if not low.endswith('.tga') or e['bytes'] != ENTRY_BYTES or e['flags']:
                continue
            if 'lightmap' in low or base in reduced or base in pinned:
                continue
            if not (WORLD.match(low) or low in EXTRA):
                continue
            chosen[base] = e['bytes']          # later archives (patch) override by name
    # Reflection/tile/blend atlases first: they were the measured reload stalls.
    ordered = sorted(chosen, key=lambda n: (0 if 'reflect' in n.lower() or n.lower() in EXTRA else 1, n))
    names, total = [], 0
    for n in ordered:
        if total + chosen[n] > BUDGET:
            break
        names.append(n); total += chosen[n]
    names.sort()
    body = '\n'.join('    "%s",' % n for n in names)
    (ROOT / 'source/gangstar_texture_hot_preload.h').write_text(f'''#ifndef GANGSTAR_TEXTURE_HOT_PRELOAD_H
#define GANGSTAR_TEXTURE_HOT_PRELOAD_H
/* Generated by tools/generate_hot_preload.py from the OBB directory. Do not edit.
 * Plain 512x512 district textures (174904-byte ETC1 DDS entries) that are not
 * reduced-LOD sources, lightmaps or retained pins. The engine streams them on
 * the frame thread while driving (~15 ms first use, 20-70 ms per reload); the
 * port loads them into its reload cache on the world loading screen. */
static const char *const rio_hot_preload_names[] = {{
{body}
}};
#define RIO_HOT_PRELOAD_COUNT (sizeof(rio_hot_preload_names) / sizeof(rio_hot_preload_names[0]))
#endif
''')
    skipped = len(chosen) - len(names)
    print(f'hot preload: {len(names)} textures, {total / 2**20:.1f} MiB'
          + (f' ({skipped} more over the {BUDGET >> 20} MiB budget skipped)' if skipped else ''))

if __name__ == '__main__':
    main()
