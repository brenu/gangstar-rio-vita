#!/usr/bin/env bash
set -euo pipefail
PROJECT_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
export VITASDK="${VITASDK:-/usr/local/vitasdk}"
export PATH="$VITASDK/bin:$PATH"

# shellcheck source=config/tested.sh
source "$PROJECT_ROOT/config/tested.sh"

# The profile is the single source of defaults; -u catches missing settings.
CMAKE_OPTIONS=(
  -DCMAKE_BUILD_TYPE=Debug
  -DUSE_SCELIBC_IO=OFF
  -DGANGSTAR_HEAP_TRACE="${GANGSTAR_HEAP_TRACE}"
  -DGANGSTAR_GRAPHICS_DIAGNOSTICS="${GANGSTAR_GRAPHICS_DIAGNOSTICS}"
  -DGANGSTAR_SHARED_ARCHIVE_CACHE="${GANGSTAR_SHARED_ARCHIVE_CACHE}"
  -DGANGSTAR_ARCHIVE_CACHE_MIB="${GANGSTAR_ARCHIVE_CACHE_MIB}"
  -DGANGSTAR_ARCHIVE_BLOCK_KIB="${GANGSTAR_ARCHIVE_BLOCK_KIB}"
  -DGANGSTAR_ARCHIVE_VIRTUAL_CURSOR="${GANGSTAR_ARCHIVE_VIRTUAL_CURSOR}"
  -DGANGSTAR_ARCHIVE_READ_POSITION_CACHE="${GANGSTAR_ARCHIVE_READ_POSITION_CACHE}"
  -DGANGSTAR_ARCHIVE_POSITION_CACHE="${GANGSTAR_ARCHIVE_POSITION_CACHE}"
  -DGANGSTAR_AUDIO_HALF_CHUNKS="${GANGSTAR_AUDIO_HALF_CHUNKS}"
  -DGANGSTAR_NATIVE_IMA_FAST="${GANGSTAR_NATIVE_IMA_FAST}"
  -DGANGSTAR_NATIVE_ADPCM_VERIFY="${GANGSTAR_NATIVE_ADPCM_VERIFY}"
  -DGANGSTAR_AUDIO_POLL_CAP="${GANGSTAR_AUDIO_POLL_CAP}"
  -DGANGSTAR_AUDIO_SCOPED_PRIORITY="${GANGSTAR_AUDIO_SCOPED_PRIORITY}"
  -DGANGSTAR_LOOSE_PATH_INDEX="${GANGSTAR_LOOSE_PATH_INDEX}"
  -DGANGSTAR_LOOSE_IO_BUFFERING="${GANGSTAR_LOOSE_IO_BUFFERING}"
  -DGANGSTAR_QUEUED_MUTEX="${GANGSTAR_QUEUED_MUTEX}"
  -DGANGSTAR_ALPHA_SUBIMAGE_OVERWRITE="${GANGSTAR_ALPHA_SUBIMAGE_OVERWRITE}"
  -DGANGSTAR_ETC1_RESERVE_MIPS="${GANGSTAR_ETC1_RESERVE_MIPS}"
  -DGANGSTAR_UPLOAD_STAGES="${GANGSTAR_UPLOAD_STAGES}"
  -DGANGSTAR_WORLD_SOURCE_PREWARM="${GANGSTAR_WORLD_SOURCE_PREWARM}"
  -DGANGSTAR_WORLD_TEXTURE_LOD="${GANGSTAR_WORLD_TEXTURE_LOD}"
  -DGANGSTAR_ASYNC_LOG="${GANGSTAR_ASYNC_LOG}"
  -DGANGSTAR_AUDIO_DIRECT_PATHS="${GANGSTAR_AUDIO_DIRECT_PATHS}"
  -DGANGSTAR_DIRECT_ASSET_PATHS="${GANGSTAR_DIRECT_ASSET_PATHS}"
  -DGANGSTAR_TEXTURE_PREWARM="${GANGSTAR_TEXTURE_PREWARM}"
  -DGANGSTAR_TEXTURE_REF_CACHE="${GANGSTAR_TEXTURE_REF_CACHE}"
  -DGANGSTAR_RESIDENT_TEXTURES="${GANGSTAR_RESIDENT_TEXTURES}"
  -DGANGSTAR_HIDE_TOUCH_BUTTONS="${GANGSTAR_HIDE_TOUCH_BUTTONS}"
  -DGANGSTAR_TEXTURE_LOD_EDGE="${GANGSTAR_TEXTURE_LOD_EDGE}"
  -DGANGSTAR_SMALL_LIGHTMAPS="${GANGSTAR_SMALL_LIGHTMAPS}"
  -DGANGSTAR_ASSET_PREFETCH="${GANGSTAR_ASSET_PREFETCH}"
  -DGANGSTAR_ARCHIVE_PREFETCH="${GANGSTAR_ARCHIVE_PREFETCH}"
  -DGANGSTAR_NATIVE_ARCHIVE_IO="${GANGSTAR_NATIVE_ARCHIVE_IO}"
  -DGANGSTAR_NATIVE_STARTUP_PROFILE="${GANGSTAR_NATIVE_STARTUP_PROFILE}"
  -DGANGSTAR_ARCHIVE_ROUTE_CACHE="${GANGSTAR_ARCHIVE_ROUTE_CACHE}"
  -DGANGSTAR_PAK_NAME_LOOKUP="${GANGSTAR_PAK_NAME_LOOKUP}"
  -DGANGSTAR_SHADER_WARMUP="${GANGSTAR_SHADER_WARMUP}"
  -DGANGSTAR_PERFORMANCE_PROFILE="${GANGSTAR_PERFORMANCE_PROFILE}"
  -DGANGSTAR_VITAGL_PROFILING="${GANGSTAR_VITAGL_PROFILING}"
  -DGANGSTAR_IO_PROFILE="${GANGSTAR_IO_PROFILE}"
  -DGANGSTAR_VITAGL_WVP_ON_GPU="${GANGSTAR_VITAGL_WVP_ON_GPU}"
  -DGANGSTAR_VITAGL_NO_TILE_CLIPPER="${GANGSTAR_VITAGL_NO_TILE_CLIPPER}"
  -DGANGSTAR_VITAGL_SKIP_ERROR_HANDLING="${GANGSTAR_VITAGL_SKIP_ERROR_HANDLING}"
  -DGANGSTAR_VITAGL_SAFE_DRAW_SPEEDHACK="${GANGSTAR_VITAGL_SAFE_DRAW_SPEEDHACK}"
  -DGANGSTAR_VITAGL_NO_DMAC="${GANGSTAR_VITAGL_NO_DMAC}"
  -DGANGSTAR_HOST_OPT_LEVEL="${GANGSTAR_HOST_OPT_LEVEL}"
)
case "${1:-}" in
  --show-config)
    printf '%s\n' "${CMAKE_OPTIONS[@]}"
    exit 0
    ;;
  --help|-h)
    printf 'Usage: bash build.sh [--show-config]\n'
    exit 0
    ;;
  '') ;;
  *) printf 'Unknown argument: %s\n' "$1" >&2; exit 2 ;;
esac
python3 "$PROJECT_ROOT/tools/preflight.py"
cmake -S "$PROJECT_ROOT" -B "$PROJECT_ROOT/work/build" "${CMAKE_OPTIONS[@]}"
python3 "$PROJECT_ROOT/tools/verify_build_config.py" "$PROJECT_ROOT/work/build" "${CMAKE_OPTIONS[@]}"
cmake --build "$PROJECT_ROOT/work/build" -j2
